/*
 * FACE VALUE — настройки системы редкости. ЕДИНСТВЕННОЕ место, где задаются вероятности.
 *
 * Как это работает: для каждого вопроса раунда сначала разыгрывается редкость
 * с этими вероятностями, затем случайно выбирается товар этой редкости
 * (среди ещё не показанных в текущем раунде).
 *
 * Чтобы поменять шансы — измените числа в WEIGHTS. Сумма должна быть равна 1 (100%).
 * Игровую логику при этом трогать не нужно. Автотесты проверят сумму и распределение.
 *
 * Редкость каждого товара задаётся вручную полем "rarity" в js/data/questions.js.
 * Если поле не указано, товар считается COMMON.
 */
(function (root) {
  var RARITY = {
    // От самой частой к самой редкой. Порядок важен для запасного выбора (fallback).
    ORDER: ["COMMON", "RARE", "EPIC", "LEGENDARY"],

    WEIGHTS: {
      COMMON: 0.90,     // 90%
      RARE: 0.07,       // 7%
      EPIC: 0.025,      // 2,5%
      LEGENDARY: 0.005  // 0,5%
    },

    DEFAULT: "COMMON",

    LABELS: {
      COMMON: "Обычный",
      RARE: "Редкий",
      EPIC: "Эпический",
      LEGENDARY: "Легендарный"
    }
  };

  if (typeof module !== "undefined" && module.exports) module.exports = RARITY;
  else root.FV_RARITY = RARITY;
})(typeof window !== "undefined" ? window : this);
